# -*- coding: utf-8 -*-
"""Assemble the Frontiers submission-form fields from the authoritative docx
and the two narrative fields, so that nothing is retyped by hand.

Output: submissions/<pkg>/06_Form_fields/Frontiers_submission_form_fields.md
Every value is copied verbatim from 课题设计阶段/manuscript_Frontiers_Methods_v2.docx
(title, authors, affiliation, word count, article type, abstract, keywords)
or from manuscript/Contribution_to_the_field.md and manuscript/Scope_statement.md.
"""
import os
import re
import sys

from docx import Document

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCX = os.path.join(ROOT, "课题设计阶段", "manuscript_Frontiers_Methods_v2.docx")
CONTRIB = os.path.join(ROOT, "manuscript", "Contribution_to_the_field.md")
SCOPE = os.path.join(ROOT, "manuscript", "Scope_statement.md")


SUP = dict(zip("0123456789+-=()ni", "⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻⁼⁽⁾ⁿⁱ"))
SUB = dict(zip("0123456789+-=()", "₀₁₂₃₄₅₆₇₈₉₊₋₌₍₎"))


def run_text(p):
    """Paragraph text with superscript/subscript runs mapped to Unicode, so that
    '10' + super('-4') becomes '10⁻⁴' and a copy-paste into a web form stays
    readable. Plain .text would flatten it to '10-4'."""
    out = []
    for r in p.runs:
        t = r.text
        if r.font.superscript:
            t = "".join(SUP.get(c, c) for c in t)
        elif r.font.subscript:
            t = "".join(SUB.get(c, c) for c in t)
        out.append(t)
    return "".join(out).strip()


def main(out_path):
    d = Document(DOCX)
    paras = [run_text(p) for p in d.paragraphs]
    nonempty = [t for t in paras if t]

    title = nonempty[0]
    authors = nonempty[1]
    affiliation = nonempty[2]
    # metadata lines
    meta = {}
    for t in nonempty[3:9]:
        m = re.match(r"^(Word count|Figures|Article type|Correspondence|Keywords)\s*:?\s*(.*)$", t)
        if m:
            meta[m.group(1).lower()] = m.group(2) if m.group(2) else t

    # abstract = everything between the 'Abstract' heading and the 'Keywords' line
    try:
        i_abs = paras.index("Abstract")
    except ValueError:
        sys.exit("no 'Abstract' heading found in %s" % DOCX)
    i_kw = next(i for i, t in enumerate(paras) if t.startswith("Keywords"))
    abstract = [t for t in paras[i_abs + 1:i_kw] if t]
    keywords = paras[i_kw].split(":", 1)[1].strip()

    contrib = open(CONTRIB, encoding="utf-8").read().strip()
    scope = open(SCOPE, encoding="utf-8").read().strip()

    lines = []
    A = lines.append
    A("# Frontiers submission form — fields to paste")
    A("")
    A("Generated by `code/build_form_fields.py` from "
      "`课题设计阶段/manuscript_Frontiers_Methods_v2.docx`, "
      "`manuscript/Contribution_to_the_field.md`, `manuscript/Scope_statement.md`.")
    A("Do not edit this file by hand: edit the sources and re-run the script.")
    A("")
    A("---")
    A("")
    A("## Article type")
    A("")
    A("Methods (original research).")
    A("")
    A("## Title")
    A("")
    A(title)
    A("")
    A("## Authors")
    A("")
    A(authors)
    A("")
    A("## Affiliation")
    A("")
    A(affiliation)
    A("")
    A("## Corresponding author")
    A("")
    A(meta.get("correspondence", "Ming Luo, lm962272@gmail.com"))
    A("")
    A("## Abstract")
    A("")
    for p in abstract:
        A(p)
        A("")
    A("## Keywords")
    A("")
    A(keywords)
    A("")
    A("## Contribution to the field")
    A("")
    A(contrib)
    A("")
    A("## Scope statement (fit to specialty)")
    A("")
    A(scope)
    A("")
    A("## Declarations carried in the manuscript")
    A("")
    A("- Word count: %s" % meta.get("word count", "see manuscript front matter"))
    A("- Data availability: Zenodo DOI 10.5281/zenodo.23733172; "
      "GitHub `ming13333/iad-falsification-framework`")
    A("- Ethics: secondary analysis of published summary-level GWAS data; "
      "no new participant data, no ethical approval required")
    A("- Funding, competing interests, author contributions, "
      "AI-use declaration: stated in the manuscript's Declarations section")
    A("")

    text = "\n".join(lines)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d chars, %d abstract paragraphs)" % (out_path, len(text), len(abstract)))
    # sanity: no stale DOI, no stale title verb
    bad = [k for k in ("21858125", "43,200-simulation validation", "for correcting") if k in text]
    if bad:
        sys.exit("STALE CONTENT in output: %s" % bad)
    print("stale-content check: PASS")


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        ROOT, "submissions", "Frontiers_1986036_revision_20261103",
        "06_Form_fields", "Frontiers_submission_form_fields.md")
    main(out)
